"""Regenerate components/warm/glass-sizes.ts from public/glass/*.webp: pixel size and a content fingerprint, so a
re-rendered image gets a new URL (encoded images are cached for 30 days). Run from the repo root."""
from PIL import Image
import glob, hashlib, os
rows = []
for f in sorted(glob.glob('public/glass/*.webp')):
    w, h = Image.open(f).size
    v = hashlib.sha1(open(f, 'rb').read()).hexdigest()[:8]
    rows.append(f"  '{os.path.basename(f)[:-5]}': [{w}, {h}, '{v}'],")
open('components/warm/glass-sizes.ts', 'w').write(
    "/** Pixel size and content fingerprint of each still glass image in public/glass/ (rendered at 2x by\n"
    " *  /preview/glass-render). Generated by the glass pipeline: rerun it whenever an image changes. */\n"
    "export const GLASS_SIZES = {\n" + "\n".join(rows) + "\n} as const;\n\nexport type GlassName = keyof typeof GLASS_SIZES;\n")
print(len(rows), 'glass images')
